PROJECT = Path(__file__).resolve().parents[1]
DATA = PROJECT / 'iphone_batch' / '.device-data'
LOG_ROOT = DATA / 'diagnostics' / 'touch'
PHONE_FILTER = re.compile(r'digitizer|unsupported service|externalAccessory|authenticat|mainTouchscreen|remote.*(?:hid|touch)', re.I)
PROCESSES = ('backboardd', 'dtuhidd')


def enabled(root=PROJECT):
    """A packaged backend must never opt into this through inherited env vars."""
    root = Path(root)
    return ((root / '.git').exists() and (root / '.venv').is_dir()
            and not (root / '8070-host-policy.json').exists()
            and os.environ.get('IPHONE_BATCH_TOUCH_TRACE', '1') != '0')


def state_of(instance):
    recv = getattr(instance, '_active_recv_task', None)
    now = time.monotonic()
    last = getattr(instance, '_last_good_au_t', 0)
    return {'generation': getattr(instance, '_batch_input_generation', 0),
            'active': bool(getattr(instance, '_batch_active', False)),
            'recovering': bool(getattr(instance, '_batch_recovering', False)),
            'contact_down': getattr(instance, '_batch_contact', None) is not None,
            'keys_down': bool(getattr(instance, '_batch_keys_down', False)),
            'uhs_connected': getattr(instance, '_uhs', None) is not None,
            'keyboard_registered': getattr(instance, '_kb_service_id', None) is not None,
            'source_active': getattr(instance, '_active_service', None) is not None,
            'receiver_done': recv.done() if recv is not None else None,
            'source_au_age_ms': round(1000 * (now - last)) if last else None}


def input_metadata(path, body):
    # Never retain key usages, clipboard contents, recipient or body text.
    result = {'path': path}
    if path in ('/manual-touch', '/touch'):
        if body.get('type') in ('contact', 'release'):
            result['type'] = body['type']
        result.update({k: body[k] for k in ('x', 'y') if type(body.get(k)) is int and 0 <= body[k] <= 65535})
        if type(body.get('settle')) is bool:
            result['settle'] = body['settle']
        result['fingers'] = 2 if 'contacts' in body else 1
    elif path in ('/manual-key', '/key'):
        result['keys_count'] = len(body['usages']) if isinstance(body.get('usages'), list) else None
    return result


class TouchTrace:
    def __init__(self, device, port, root=LOG_ROOT, max_bytes=2 * 1024 * 1024):
        if not re.fullmatch(r'[A-Za-z0-9-]{4,80}', device):
            raise ValueError('Invalid trace device')
        self.device, self.port = device, port
        self.session = uuid.uuid4().hex
        self.path = Path(root) / (device + '.jsonl')
        self.max_bytes = max_bytes
        self.events = deque(maxlen=128)
        self.pending = queue.Queue(maxsize=2048)
        self.dropped = 0
        self.io_error = None
        self.collector_state = 'stopped'
        self.collector_error = None
        self.phone_lines = 0
        self.task = None
        self.process = None
        self.sequence = 0
        self.closed = False
        self.wanted = False
        self.stop_writer = threading.Event()
        self.worker = threading.Thread(target=self._write, name='touch-trace-writer', daemon=True)
        self.worker.start()
        self.record('session-start', pid=os.getpid(), port=port)

    def record(self, kind, **fields):
        if self.closed:
            return
        self.sequence += 1
        item = {'at': datetime.now(timezone.utc).isoformat(timespec='milliseconds'),
                'monotonic': round(time.monotonic(), 6), 'session': self.session,
                'seq': self.sequence, 'device': self.device, 'kind': kind, **fields}
        self.events.append(item)
        try:
            self.pending.put_nowait(item)
        except queue.Full:
            self.dropped += 1

    def _write(self):
        handler = None
        try:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            handler = RotatingFileHandler(self.path, maxBytes=self.max_bytes, backupCount=2, encoding='utf-8')
            handler.setFormatter(logging.Formatter('%(message)s'))
            handler.handleError = lambda record: setattr(self, 'io_error', 'LogWriteError')
            while not (self.stop_writer.is_set() and self.pending.empty()):
                try:
                    item = self.pending.get(timeout=.1)
                except queue.Empty:
                    continue
                try:
                    if item is None:
                        return
                    if isinstance(item, threading.Event):
                        handler.flush()
                        item.set()
                    else:
                        handler.emit(logging.LogRecord('touch', logging.INFO, '', 0,
                            json.dumps(item, ensure_ascii=False), (), None))
                finally:
                    self.pending.task_done()
        except Exception as error:
            self.io_error = type(error).__name__
        finally:
            if handler:
                handler.close()

    async def flush(self):
        barrier = threading.Event()
        try:
            self.pending.put_nowait(barrier)
        except queue.Full:
            return False
        return await asyncio.to_thread(barrier.wait, 2)

    def set_active(self, active):
        self.wanted = bool(active)
        if self.closed:
            return
        if active and (self.task is None or self.task.done()):
            self.task = asyncio.create_task(self._collect())
            self.task.add_done_callback(lambda task: self.set_active(True) if self.wanted and not self.closed else None)
        elif not active and self.task is not None:
            self.task.cancel()

    async def _collect(self):
        from controller import device_environment
        delay = 1
        try:
            while True:
                self.collector_state = 'starting'
                try:
                    # The screen server uses WindowsSelectorEventLoop, which
                    # has no asyncio subprocess transport. Keep blocking pipe
                    # operations in the executor so input dispatch stays free.
                    launching = asyncio.create_task(asyncio.to_thread(subprocess.Popen,
                        [sys.executable, str(PROJECT / 'iphone_batch' / 'pmd_entry.py'),
                         'trace-touch', '--udid', self.device],
                        stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                        stderr=subprocess.DEVNULL, env=device_environment(self.device),
                        creationflags=0x08000000 if os.name == 'nt' else 0))
                    try:
                        self.process = await asyncio.shield(launching)
                    except asyncio.CancelledError:
                        # Claim an already-starting child before cancellation so
                        # the finally block can close its pipe and reap it.
                        self.process = await launching
                        raise
                    self.record('collector-start', pid=self.process.pid)
                    while line := await asyncio.to_thread(self.process.stdout.readline):
                        event = json.loads(line)
                        kind = event.pop('kind')
                        if kind == 'phone-log':
                            self.phone_lines += 1
                            self.collector_state = 'streaming'
                        elif kind == 'collector-ready':
                            self.collector_state = 'listening'
                            self.collector_error = None
                            delay = 1
                        elif kind == 'collector-error':
                            self.collector_error = event.get('error')
                        self.record(kind, **event)
                    raise ConnectionError('Trace collector exited')
                except asyncio.CancelledError:
                    raise
                except Exception as error:
                    self.collector_state = 'retrying'
                    self.collector_error = type(error).__name__
                    self.record('collector-retry', error=self.collector_error, delay=delay)
                finally:
                    await self._stop_child()
                await asyncio.sleep(delay)
                delay = min(30, delay * 2)
        finally:
            self.collector_state = 'stopped'
            self.record('collector-stopped')

    async def _stop_child(self):
        process, self.process = self.process, None
        if process is None:
            return
        # EOF also shuts down the real interpreter behind Windows venv launchers.
        if process.stdin:
            try:
                process.stdin.close()
            except OSError:
                pass
        try:
            await asyncio.to_thread(process.wait, timeout=3)
        except subprocess.TimeoutExpired:
            from owned_viewer_process import stop_tree
            await asyncio.to_thread(stop_tree, process.pid,
                PROJECT / 'iphone_batch' / 'pmd_entry.py', self.device)
            await asyncio.to_thread(process.wait, timeout=3)
        finally:
            process.stdout.close()

    def status(self):
        return {'enabled': True, 'device': self.device, 'session': self.session,
                'file': str(self.path), 'collector': self.collector_state,
                'collector_error': self.collector_error, 'phone_lines': self.phone_lines,
                'dropped': self.dropped, 'io_error': self.io_error,
                'events': list(self.events), 'meaning': 'Transport acknowledgements do not prove UI action or delivery.'}

    async def close(self):
        if self.closed:
            return
        self.wanted = False
        if self.task:
            self.task.cancel()
            await asyncio.gather(self.task, return_exceptions=True)
        self.record('session-end')
        await self.flush()
        self.closed = True
        self.stop_writer.set()
        try:
            self.pending.put_nowait(None)
        except queue.Full:
            pass
        await asyncio.to_thread(self.worker.join, 2)


def trace_for(instance):
    trace = getattr(instance, '_batch_touch_trace', None)
    if trace is not None:
        return trace
    device = getattr(instance, '_batch_udid', None) or os.environ.get('PYMOBILEDEVICE3_UDID')
    if not device or not enabled():
        return None
    try:
        trace = TouchTrace(device, getattr(instance, '_http_port', None))
        instance._batch_touch_trace = trace
        return trace
    except Exception:
        logging.getLogger(__name__).exception('Touch recorder could not initialize')
        return None


def record(instance, kind, **fields):
    trace = trace_for(instance)
    if trace:
        trace.record(kind, state=state_of(instance), **fields)


BROWSER_EVENTS = frozenset(('pointer-down', 'pointer-up', 'pointer-blocked', 'pointer-busy',
    'pointer-end', 'pointer-cancel', 'home', 'input-error', 'health-change'))
BROWSER_FIELDS = frozenset(('button', 'pointer_id', 'active_pointer', 'input_ready',
    'batch_active', 'pointer_running', 'pointer_active', 'queue', 'at', 'monotonic',
    'client_at_ms', 'client_monotonic_ms', 'dropped'))


async def diagnostic_request(instance, reader, writer, method, headers, reply):
    trace = trace_for(instance)
    if trace is None:
        return await reply(writer, 404, {'enabled': False})
    try:
        if method == 'GET':
            return await reply(writer, 200, {**trace.status(), 'state': state_of(instance)})
        if method != 'POST':
            return await reply(writer, 405, {'error': 'POST or GET required'})
        length = int(headers.get('content-length', '0'))
        if not 0 < length <= 16384:
            raise ValueError('Invalid diagnostic size')
        body = json.loads(await asyncio.wait_for(reader.readexactly(length), 3))
        if not isinstance(body, dict):
            raise ValueError('Invalid diagnostic payload')
        if body.get('action') == 'mark':
            label = body.get('label')
            if not isinstance(label, str) or not re.fullmatch(r'[a-zA-Z0-9_-]{1,64}', label):
                raise ValueError('Invalid marker')
            record(instance, 'incident-marker', label=label)
            flushed = await trace.flush()
            return await reply(writer, 200, {**trace.status(), 'flushed': flushed, 'state': state_of(instance)})
        if body.get('action') != 'browser' or not isinstance(body.get('events'), list) or len(body['events']) > 48:
            raise ValueError('Invalid browser diagnostic events')
        for event in body['events']:
            if not isinstance(event, dict) or event.get('event') not in BROWSER_EVENTS:
                raise ValueError('Invalid browser diagnostic event')
            numeric = {key: value for key, value in event.items() if key in BROWSER_FIELDS
                       and type(value) in (bool, int, float) and abs(value) <= 10 ** 15}
            for old, new in (('at', 'client_at_ms'), ('monotonic', 'client_monotonic_ms')):
                if old in numeric:
                    numeric[new] = numeric.pop(old)
            trace.record('browser', event=event['event'], **numeric)
        return await reply(writer, 200, {'ok': True})
    except (ValueError, TypeError, asyncio.IncompleteReadError, asyncio.TimeoutError):
        return await reply(writer, 400, {'error': 'Invalid diagnostic request'})


async def collect_phone(device):
    """Owned subprocess: existing USB trust only; fresh, filtered system logs."""
    from pairing_patch import open_paired_usb
    from pymobiledevice3.services.os_trace import OsTraceService, OsActivityStreamFlag, OS_TRACE_RELAY_STREAM_FLAGS_DEFAULT
    def emit(kind, **fields):
        print(json.dumps({'kind': kind, **fields}, ensure_ascii=True), flush=True)
    stop = asyncio.Event()
    loop = asyncio.get_running_loop()
    def watch_parent():
        while os.read(sys.stdin.fileno(), 4096):
            pass
        try:
            loop.call_soon_threadsafe(stop.set)
        except RuntimeError:
            pass
    threading.Thread(target=watch_parent, daemon=True).start()
    async def stream():
        ld = await open_paired_usb(device, DATA)
        try:
            async with OsTraceService(ld) as trace:
                rows = (await asyncio.wait_for(trace.get_pid_list(), 4))['Payload']
            pids = {row['ProcessName']: int(pid) for pid, row in rows.items() if row.get('ProcessName') in PROCESSES}
            if 'backboardd' not in pids:
                raise RuntimeError('BackboardProcessMissing')
            emit('collector-ready', processes=pids)
            async def read_process(name, pid):
                async with OsTraceService(ld) as service:
                    flags = (OS_TRACE_RELAY_STREAM_FLAGS_DEFAULT & ~OsActivityStreamFlag.HISTORICAL) | OsActivityStreamFlag.NO_SENSITIVE
                    async for entry in service.syslog(pid=pid, stream_flags=flags):
                        if entry.pid == pid and PHONE_FILTER.search(entry.message):
                            emit('phone-log', process=name, pid=entry.pid,
                                 phone_at=entry.timestamp.astimezone(timezone.utc).isoformat(), level=str(entry.level),
                                 message=entry.message[:1800])
            tasks = [asyncio.create_task(read_process(name, pid)) for name, pid in pids.items()]
            try:
                await asyncio.gather(*tasks)
            finally:
                for task in tasks:
                    task.cancel()
                await asyncio.gather(*tasks, return_exceptions=True)
        finally:
            await ld.close()
    work, ended = asyncio.create_task(stream()), asyncio.create_task(stop.wait())
    try:
        await asyncio.wait((work, ended), return_when=asyncio.FIRST_COMPLETED)
        if work.done():
            await work
    except Exception as error:
        emit('collector-error', error=type(error).__name__)
    finally:
        work.cancel()
        ended.cancel()
        await asyncio.gather(work, ended, return_exceptions=True)


def export_bundle(device, output, status=None):
    if not re.fullmatch(r'[A-Za-z0-9-]{4,80}', device):
        raise ValueError('Invalid device')
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, 'x', compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr('status.json', json.dumps(status or {}, ensure_ascii=False, indent=2))
        archive.writestr('README.txt', 'Compare UTC at, phone_at, session and request_id. HTTP 200 is transport ACK only. Log buffering may delay phone records. Missing phone logs are not proof of rejected touches. No input is replayed.\n')
        for suffix in ('.2', '.1', ''):
            path = LOG_ROOT / (device + '.jsonl' + suffix)
            if path.is_file():
                archive.write(path, path.name)
    return output


def main():
    parser = argparse.ArgumentParser(description='8070 development touch recorder; never sends phone input')
    parser.add_argument('action', choices=('status', 'mark', 'export'))
    parser.add_argument('--number', type=int, required=True)
    parser.add_argument('--label', default='left-click-dead')
    parser.add_argument('--port', type=int, default=8070)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    from workspace_access import signed_opener
    import urllib.request
    opener = signed_opener()
    live_error = None
    try:
        state = json.load(opener.open(f'http://127.0.0.1:{args.port}/api/state', timeout=5))
        device = next(d for d in state['devices'] if int(d['number']) == args.number)
    except Exception as error:
        live_error = type(error).__name__
        rows = json.loads((DATA / 'workspace' / 'device-map.json').read_text(encoding='utf-8'))
        device = next(d for d in rows if int(d['number']) == args.number)
    status = {'device': device['udid'], 'live_error': live_error}
    try:
        url = f"http://127.0.0.1:{device['port']}/touch-diagnostics"
        if args.action in ('mark', 'export'):
            body = json.dumps({'action': 'mark', 'label': args.label}).encode()
            request = urllib.request.Request(url, data=body, headers={'Content-Type': 'application/json'})
            status = json.load(opener.open(request, timeout=8))
        else:
            status = json.load(opener.open(url, timeout=5))
    except Exception as error:
        status['live_error'] = type(error).__name__
        if args.action != 'export':
            print(json.dumps(status, ensure_ascii=False))
            raise SystemExit(1)
    if args.action == 'export':
        stamp = datetime.now().strftime('%Y%m%d-%H%M%S-%f')
        output = args.output or LOG_ROOT / 'exports' / f"device-{args.number:02}-{stamp}.zip"
        print(export_bundle(device['udid'], output, status))
    else:
        print(json.dumps(status, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
